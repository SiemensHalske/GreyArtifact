BEGIN;

CREATE SCHEMA recon;

CREATE TABLE recon.projects (
    project_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    slug TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT projects_slug_not_blank CHECK (btrim(slug) <> ''),
    CONSTRAINT projects_name_not_blank CHECK (btrim(name) <> '')
);

CREATE TABLE recon.tools (
    tool_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name TEXT NOT NULL UNIQUE,
    vendor TEXT,
    CONSTRAINT tools_name_not_blank CHECK (btrim(name) <> '')
);

CREATE TABLE recon.artifacts (
    artifact_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    sha256 CHAR(64) NOT NULL UNIQUE,
    storage_key TEXT NOT NULL UNIQUE,
    byte_size BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT artifacts_sha256_format CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    CONSTRAINT artifacts_storage_key_not_blank CHECK (btrim(storage_key) <> ''),
    CONSTRAINT artifacts_byte_size_nonnegative CHECK (byte_size >= 0)
);

CREATE TABLE recon.imports (
    import_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    project_id UUID NOT NULL REFERENCES recon.projects (project_id),
    artifact_id UUID NOT NULL REFERENCES recon.artifacts (artifact_id),
    tool_id UUID REFERENCES recon.tools (tool_id),
    tool_version TEXT,
    original_filename TEXT NOT NULL,
    media_type TEXT,
    parser_name TEXT,
    parser_version TEXT,
    imported_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status TEXT NOT NULL DEFAULT 'pending',
    error_message TEXT,
    CONSTRAINT imports_original_filename_not_blank
        CHECK (btrim(original_filename) <> ''),
    CONSTRAINT imports_status_valid
        CHECK (status IN ('pending', 'completed', 'failed'))
);

CREATE TABLE recon.asset_types (
    asset_type_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    label TEXT NOT NULL,
    CONSTRAINT asset_types_code_not_blank CHECK (btrim(code) <> ''),
    CONSTRAINT asset_types_label_not_blank CHECK (btrim(label) <> '')
);

CREATE TABLE recon.assets (
    asset_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    asset_type_id SMALLINT NOT NULL REFERENCES recon.asset_types (asset_type_id),
    canonical_value TEXT NOT NULL,
    display_value TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT assets_type_canonical_value_unique
        UNIQUE (asset_type_id, canonical_value),
    CONSTRAINT assets_canonical_value_not_blank
        CHECK (btrim(canonical_value) <> ''),
    CONSTRAINT assets_display_value_not_blank
        CHECK (btrim(display_value) <> '')
);

CREATE TABLE recon.project_assets (
    project_id UUID NOT NULL REFERENCES recon.projects (project_id),
    asset_id UUID NOT NULL REFERENCES recon.assets (asset_id),
    added_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (project_id, asset_id)
);

CREATE TABLE recon.property_types (
    property_type_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    label TEXT NOT NULL,
    value_kind TEXT NOT NULL,
    CONSTRAINT property_types_code_not_blank CHECK (btrim(code) <> ''),
    CONSTRAINT property_types_label_not_blank CHECK (btrim(label) <> ''),
    CONSTRAINT property_types_value_kind_valid
        CHECK (value_kind IN ('text', 'number', 'boolean'))
);

CREATE TABLE recon.asset_property_observations (
    observation_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    import_id UUID NOT NULL REFERENCES recon.imports (import_id),
    asset_id UUID NOT NULL REFERENCES recon.assets (asset_id),
    property_type_id SMALLINT NOT NULL
        REFERENCES recon.property_types (property_type_id),
    value_text TEXT NOT NULL,
    observed_at TIMESTAMPTZ,
    confidence NUMERIC(5, 4),
    evidence_locator TEXT,
    CONSTRAINT asset_property_observations_confidence_range
        CHECK (confidence IS NULL OR confidence BETWEEN 0 AND 1)
);

COMMENT ON TABLE recon.asset_property_observations IS
    'Application imports must ensure the asset belongs to the project referenced by the observation import.';

CREATE TABLE recon.relationship_types (
    relationship_type_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    label TEXT NOT NULL,
    CONSTRAINT relationship_types_code_not_blank CHECK (btrim(code) <> ''),
    CONSTRAINT relationship_types_label_not_blank CHECK (btrim(label) <> '')
);

CREATE TABLE recon.asset_relationship_observations (
    observation_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    import_id UUID NOT NULL REFERENCES recon.imports (import_id),
    source_asset_id UUID NOT NULL REFERENCES recon.assets (asset_id),
    relationship_type_id SMALLINT NOT NULL
        REFERENCES recon.relationship_types (relationship_type_id),
    target_asset_id UUID NOT NULL REFERENCES recon.assets (asset_id),
    observed_at TIMESTAMPTZ,
    confidence NUMERIC(5, 4),
    evidence_locator TEXT,
    CONSTRAINT asset_relationship_observations_distinct_assets
        CHECK (source_asset_id <> target_asset_id),
    CONSTRAINT asset_relationship_observations_confidence_range
        CHECK (confidence IS NULL OR confidence BETWEEN 0 AND 1)
);

COMMENT ON TABLE recon.asset_relationship_observations IS
    'Application imports must ensure both assets belong to the project referenced by the observation import.';

CREATE INDEX imports_project_imported_at_idx
    ON recon.imports (project_id, imported_at DESC);
CREATE INDEX imports_artifact_id_idx
    ON recon.imports (artifact_id);

CREATE INDEX project_assets_asset_id_idx
    ON recon.project_assets (asset_id);

CREATE INDEX asset_property_observations_import_id_idx
    ON recon.asset_property_observations (import_id);
CREATE INDEX asset_property_observations_asset_property_observed_idx
    ON recon.asset_property_observations
       (asset_id, property_type_id, observed_at DESC);

CREATE INDEX asset_relationship_observations_import_id_idx
    ON recon.asset_relationship_observations (import_id);
CREATE INDEX asset_relationship_observations_source_type_target_idx
    ON recon.asset_relationship_observations
       (source_asset_id, relationship_type_id, target_asset_id);
CREATE INDEX asset_relationship_observations_target_id_idx
    ON recon.asset_relationship_observations (target_asset_id);

INSERT INTO recon.asset_types (code, label)
VALUES
    ('domain', 'Domain'),
    ('ipv4', 'IPv4 address'),
    ('ipv6', 'IPv6 address'),
    ('network', 'Network'),
    ('url', 'URL'),
    ('email', 'Email address'),
    ('tls_certificate', 'TLS certificate'),
    ('service_endpoint', 'Service endpoint'),
    ('file_hash', 'File hash')
ON CONFLICT (code) DO NOTHING;

INSERT INTO recon.relationship_types (code, label)
VALUES
    ('resolves_to', 'Resolves to'),
    ('hosts', 'Hosts'),
    ('references', 'References')
ON CONFLICT (code) DO NOTHING;

COMMIT;
