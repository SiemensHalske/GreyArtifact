BEGIN;

CREATE TABLE recon.scopes (
    scope_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name TEXT NOT NULL UNIQUE,
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT scopes_name_not_blank CHECK (btrim(name) <> '')
);

INSERT INTO recon.scopes (name, description)
VALUES ('default', 'Default scope for data created before scope support.')
ON CONFLICT (name) DO NOTHING;

ALTER TABLE recon.projects
    ADD COLUMN scope_id UUID;

UPDATE recon.projects
SET scope_id = (SELECT scope_id FROM recon.scopes WHERE name = 'default')
WHERE scope_id IS NULL;

ALTER TABLE recon.projects
    ALTER COLUMN scope_id SET NOT NULL,
    ADD CONSTRAINT projects_scope_id_fkey
        FOREIGN KEY (scope_id) REFERENCES recon.scopes (scope_id);

ALTER TABLE recon.projects
    DROP CONSTRAINT projects_slug_key,
    ADD CONSTRAINT projects_scope_slug_unique UNIQUE (scope_id, slug);

CREATE TABLE recon.principals (
    principal_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    username TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    display_name TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT principals_username_not_blank CHECK (btrim(username) <> ''),
    CONSTRAINT principals_password_hash_not_blank
        CHECK (btrim(password_hash) <> '')
);

CREATE TABLE recon.roles (
    role_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    label TEXT NOT NULL,
    CONSTRAINT roles_code_not_blank CHECK (btrim(code) <> ''),
    CONSTRAINT roles_label_not_blank CHECK (btrim(label) <> '')
);

CREATE TABLE recon.permissions (
    permission_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    label TEXT NOT NULL,
    CONSTRAINT permissions_code_not_blank CHECK (btrim(code) <> ''),
    CONSTRAINT permissions_label_not_blank CHECK (btrim(label) <> '')
);

CREATE TABLE recon.role_permissions (
    role_id SMALLINT NOT NULL REFERENCES recon.roles (role_id) ON DELETE CASCADE,
    permission_id SMALLINT NOT NULL
        REFERENCES recon.permissions (permission_id) ON DELETE CASCADE,
    PRIMARY KEY (role_id, permission_id)
);

CREATE TABLE recon.scope_memberships (
    scope_id UUID NOT NULL REFERENCES recon.scopes (scope_id) ON DELETE CASCADE,
    principal_id UUID NOT NULL
        REFERENCES recon.principals (principal_id) ON DELETE CASCADE,
    role_id SMALLINT NOT NULL REFERENCES recon.roles (role_id),
    granted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    granted_by UUID REFERENCES recon.principals (principal_id),
    PRIMARY KEY (scope_id, principal_id, role_id)
);

CREATE INDEX scope_memberships_principal_id_idx
    ON recon.scope_memberships (principal_id);

INSERT INTO recon.permissions (code, label)
VALUES
    ('scope.read', 'Read scope content'),
    ('scope.manage', 'Manage scope settings'),
    ('membership.manage', 'Manage scope memberships'),
    ('project.manage', 'Create and manage projects'),
    ('data.read', 'Read imported data'),
    ('data.import', 'Import and modify data'),
    ('data.delete', 'Delete imported data'),
    ('pipeline.execute', 'Execute data-processing pipelines'),
    ('pipeline.manage', 'Create and manage pipelines')
ON CONFLICT (code) DO NOTHING;

INSERT INTO recon.roles (code, label)
VALUES
    ('viewer', 'Viewer'),
    ('analyst', 'Analyst'),
    ('owner', 'Scope owner')
ON CONFLICT (code) DO NOTHING;

INSERT INTO recon.role_permissions (role_id, permission_id)
SELECT r.role_id, p.permission_id
FROM recon.roles AS r
CROSS JOIN recon.permissions AS p
WHERE (r.code = 'viewer'
       AND p.code IN ('scope.read', 'data.read'))
   OR (r.code = 'analyst'
       AND p.code IN (
           'scope.read',
           'project.manage',
           'data.read',
           'data.import',
           'pipeline.execute'
       ))
   OR (r.code = 'owner'
       AND p.code IN (
           'scope.read',
           'scope.manage',
           'membership.manage',
           'project.manage',
           'data.read',
           'data.import',
           'data.delete',
           'pipeline.execute',
           'pipeline.manage'
       ))
ON CONFLICT DO NOTHING;

CREATE TABLE recon.pipelines (
    pipeline_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    scope_id UUID NOT NULL REFERENCES recon.scopes (scope_id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    description TEXT,
    is_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_by UUID REFERENCES recon.principals (principal_id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pipelines_scope_name_unique UNIQUE (scope_id, name),
    CONSTRAINT pipelines_name_not_blank CHECK (btrim(name) <> '')
);

CREATE TABLE recon.pipeline_operations (
    operation_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    label TEXT NOT NULL,
    access_mode TEXT NOT NULL,
    required_permission_id SMALLINT NOT NULL
        REFERENCES recon.permissions (permission_id),
    CONSTRAINT pipeline_operations_code_not_blank CHECK (btrim(code) <> ''),
    CONSTRAINT pipeline_operations_label_not_blank CHECK (btrim(label) <> ''),
    CONSTRAINT pipeline_operations_access_mode_valid
        CHECK (access_mode IN ('read', 'write', 'read_write'))
);

CREATE TABLE recon.pipeline_steps (
    pipeline_id UUID NOT NULL
        REFERENCES recon.pipelines (pipeline_id) ON DELETE CASCADE,
    step_number INTEGER NOT NULL,
    operation_id SMALLINT NOT NULL
        REFERENCES recon.pipeline_operations (operation_id),
    configuration JSONB NOT NULL DEFAULT '{}'::jsonb,
    PRIMARY KEY (pipeline_id, step_number),
    CONSTRAINT pipeline_steps_number_positive CHECK (step_number > 0),
    CONSTRAINT pipeline_steps_configuration_object
        CHECK (jsonb_typeof(configuration) = 'object')
);

CREATE TABLE recon.pipeline_runs (
    run_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    pipeline_id UUID NOT NULL REFERENCES recon.pipelines (pipeline_id),
    triggered_by UUID NOT NULL REFERENCES recon.principals (principal_id),
    status TEXT NOT NULL DEFAULT 'pending',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    started_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ,
    error_message TEXT,
    CONSTRAINT pipeline_runs_status_valid
        CHECK (status IN ('pending', 'running', 'succeeded', 'failed', 'cancelled')),
    CONSTRAINT pipeline_runs_time_order
        CHECK (finished_at IS NULL OR started_at IS NULL OR finished_at >= started_at)
);

CREATE INDEX pipeline_runs_pipeline_created_idx
    ON recon.pipeline_runs (pipeline_id, created_at DESC);

CREATE TABLE recon.pipeline_run_steps (
    run_id UUID NOT NULL REFERENCES recon.pipeline_runs (run_id) ON DELETE CASCADE,
    step_number INTEGER NOT NULL,
    operation_code TEXT NOT NULL,
    configuration_snapshot JSONB NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending',
    started_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ,
    error_message TEXT,
    PRIMARY KEY (run_id, step_number),
    CONSTRAINT pipeline_run_steps_number_positive CHECK (step_number > 0),
    CONSTRAINT pipeline_run_steps_configuration_object
        CHECK (jsonb_typeof(configuration_snapshot) = 'object'),
    CONSTRAINT pipeline_run_steps_status_valid
        CHECK (status IN ('pending', 'running', 'succeeded', 'failed', 'skipped')),
    CONSTRAINT pipeline_run_steps_time_order
        CHECK (finished_at IS NULL OR started_at IS NULL OR finished_at >= started_at)
);

INSERT INTO recon.pipeline_operations
    (code, label, access_mode, required_permission_id)
SELECT op.code,
       op.label,
       op.access_mode,
       p.permission_id
FROM (VALUES
    ('artifact.validate', 'Validate imported artifact', 'read', 'data.read'),
    ('report.parse', 'Parse an imported report', 'read_write', 'data.import'),
    ('observations.normalize', 'Normalize observations', 'read_write', 'data.import'),
    ('markdown.export', 'Export data as Markdown', 'read', 'data.read')
) AS op(code, label, access_mode, permission_code)
JOIN recon.permissions AS p
    ON p.code = op.permission_code
ON CONFLICT (code) DO NOTHING;

COMMENT ON TABLE recon.scopes IS
    'Top-level workspace boundary; permissions are granted through scope_memberships.';
COMMENT ON TABLE recon.assets IS
    'Assets are globally deduplicated; access must be scoped through projects and project_assets.';
COMMENT ON TABLE recon.pipeline_operations IS
    'Allow-listed data-processing operations only; pipeline steps must never launch scanners or arbitrary shell commands.';
COMMENT ON COLUMN recon.pipeline_steps.configuration IS
    'Operation-specific configuration; JSONB is intentionally used for extensible pipeline parameters.';
COMMENT ON COLUMN recon.pipeline_run_steps.configuration_snapshot IS
    'Immutable parameter snapshot for auditability; JSONB is intentionally used as a run-time snapshot.';

COMMIT;
